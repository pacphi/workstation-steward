// The engine's defaults keep up with what's qualified: the AQE release the example instance names ([aqe] based_on) has
// its vendor files listed in known-vendor-files.toml (D25), or onboarding after the next upgrade would treat unedited
// copies of them as edited and keep them (missed for 3.15.16 on 2026-10-30). No network. Run: just test
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const F = require('../lib/profiles.js');

const REPO = path.join(__dirname, '..');
const VENDOR = ['.claude/helpers/brain-checkpoint.cjs', '.claude/hooks/aqe-hook.cjs'];

// num(v) — [major, minor, patch] of "3.15.16" or "3.15.16-local.1"
const num = v => v.split('-')[0].split('.').map(Number);
const cmp = (a, b) => { const x = num(a), y = num(b); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0; };

// covers(origin, v) — the origin names v, or a range "a … b" that holds it ("shipped: 3.15.3 … 3.15.12-local.1")
function covers(origin, v) {
  const list = origin.replace(/^[^:]*:\s*/, '').replace(/\s*\(.*\)$/, '');
  return list.split(/,\s*/).some(part => {
    const [a, b] = part.split(/\s*…\s*/);
    if (!/^\d/.test(a)) return false;
    return b ? cmp(a, v) <= 0 && cmp(v, b) <= 0 : cmp(a, v) === 0;
  });
}

test('covers: single versions, lists and ranges, with or without a -local suffix', () => {
  assert.equal(covers('shipped: 3.15.3 … 3.15.12-local.1', '3.15.12'), true);
  assert.equal(covers('shipped: 3.15.3 … 3.15.12-local.1', '3.15.7'), true);
  assert.equal(covers('shipped: 3.15.3 … 3.15.12-local.1', '3.15.16'), false);
  assert.equal(covers('shipped: 3.14.6, 3.15.0', '3.15.0'), true);
  assert.equal(covers('shipped: 3.15.16, 3.15.16-local.1 (the official tarball and the runtime agree)', '3.15.16'), true);
  assert.equal(covers('generated by aqe init: 3.7.21', '3.7.20'), false);
});

test('known-vendor-files.toml lists both AQE vendor files for the release the example instance is based on', () => {
  const toml = fs.readFileSync(path.join(REPO, 'examples', 'ai-tooling', 'ai-tooling.toml'), 'utf8');
  const basedOn = (toml.match(/^based_on\s*=\s*"([^"]+)"/m) || [])[1];
  assert.ok(basedOn, 'examples/ai-tooling/ai-tooling.toml has an [aqe] based_on');
  const known = [...F.knownVendor().values()];
  for (const file of VENDOR) {
    assert.ok(known.some(e => e.file === file && covers(e.origin, basedOn)),
      `${file}: no entry for AQE ${basedOn}; add its hash from the official tarball (skills/ai-tooling/qualification.md, AQE step 8)`);
  }
});
